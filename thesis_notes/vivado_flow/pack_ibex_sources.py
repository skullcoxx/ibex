#!/usr/bin/env python3
"""
Pack the synthesizable Ibex sources of one build into a folder for Vivado.

Run on the machine that has the FuseSoC build (the department machine). It reads the build's
*.eda.yml (the exact file list and order used for the simulator), keeps only synthesizable RTL,
swaps the generic clock-gating cell for the Xilinx one (BUFGCE), and writes a small wrapper
(ibex_syn_top.sv) that instantiates ibex_top with the FPGA register file.

Usage:
  pack_ibex_sources.py --builddir <.../build/lowrisc_ibex_ibex_simple_system_0/sim-verilator>
                       --repo <ibex repo> --out <output folder> [--lut-sbox] [--generic-clock-gating]

  --lut-sbox              set the AES unit's SBOX_COMPACT default to 0 (lookup-table S-box)
  --generic-clock-gating  keep the generic (latch based) clock gate; only useful for non-Vivado lint
  --zip                   also create <out>.zip (copy this one file to the machine running Vivado)
"""
import argparse, glob, os, re, shutil, sys
import yaml

EXCLUDE_CORES = {
    "lowrisc:ibex:sim_shared:0", "lowrisc:ibex:ibex_tracer:0.1", "lowrisc:ibex:ibex_top_tracing:0.1",
    "lowrisc:ibex:ibex_simple_system_core:0", "lowrisc:ibex:ibex_simple_system:0",
    "lowrisc:prim:cdc_rand_delay:0",
}
EXCLUDE_PREFIXES = ("lowrisc:dv:", "lowrisc:dv_verilator:", "lowrisc:lint:", "lowrisc:tool:")

def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)

def match_paren(s, i):
    """s[i] == '(' -> index of the matching ')'"""
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "(": depth += 1
        elif s[j] == ")":
            depth -= 1
            if depth == 0: return j
    raise ValueError("unbalanced parentheses")

def make_wrapper(ibex_top_path):
    src = strip_comments(open(ibex_top_path).read())
    m = re.search(r"\bmodule\s+ibex_top\b", src)
    if not m: raise SystemExit("ibex_top module not found in " + ibex_top_path)
    hdr_start = m.end()
    p_hash = src.index("#(", hdr_start)
    imports = src[hdr_start:p_hash].strip()                      # e.g. "import ibex_pkg::*; import ..."
    p_params_end = match_paren(src, p_hash + 1)
    p_ports = src.index("(", p_params_end)
    p_ports_end = match_paren(src, p_ports)
    ports = src[p_ports + 1:p_ports_end]
    # drop blank lines left behind by comment stripping
    ports = "\n".join(l.rstrip() for l in ports.splitlines() if l.strip())
    return f"""// Generated by pack_ibex_sources.py -- synthesis wrapper for out-of-context Vivado runs.
// Same ports as ibex_top; only the register file implementation is overridden (FPGA RAM based).
module ibex_syn_top {imports} (
{ports}
);

  ibex_top #(
    .RegFile (ibex_pkg::RegFileFPGA)
  ) u_ibex_top (.*);

endmodule
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--builddir", required=True)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lut-sbox", action="store_true")
    ap.add_argument("--generic-clock-gating", action="store_true")
    ap.add_argument("--zip", action="store_true", help="also write <out>.zip")
    a = ap.parse_args()

    ymls = glob.glob(os.path.join(a.builddir, "*.eda.yml"))
    if len(ymls) != 1: sys.exit(f"expected exactly one *.eda.yml in {a.builddir}, found {ymls}")
    d = yaml.safe_load(open(ymls[0]))

    out = os.path.abspath(a.out)
    if os.path.exists(out): shutil.rmtree(out)
    os.makedirs(out)

    read_list, inc_dirs = [], []
    n_skipped = 0
    for f in d["files"]:
        core = f.get("core", "")
        if f.get("file_type") != "systemVerilogSource": continue
        # Sim/DV-only cores are dropped, except their include headers (e.g. dv_fcov_macros.svh is
        # `included by ibex_controller.sv and expands to nothing without coverage defines).
        if (core in EXCLUDE_CORES or core.startswith(EXCLUDE_PREFIXES)) and not f.get("is_include_file"):
            n_skipped += 1; continue
        rel = f["name"]
        src = os.path.join(a.builddir, rel)
        if not os.path.isfile(src): sys.exit("missing source file: " + src)
        if rel.endswith("prim_clock_gating.sv") and not a.generic_clock_gating:
            xil = os.path.join(a.repo, "vendor/lowrisc_ip/ip/prim_xilinx/rtl/prim_clock_gating.sv")
            if not os.path.isfile(xil): sys.exit("Xilinx clock gating file not found: " + xil)
            src = xil
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        if f.get("is_include_file"):
            inc = os.path.dirname(rel)
            if inc not in inc_dirs: inc_dirs.append(inc)
        else:
            read_list.append(rel)

    if a.lut_sbox:
        p = os.path.join(out, [r for r in read_list if r.endswith("aes_v3_fu.sv")][0])
        s = open(p).read()
        new = s.replace("parameter bit SBOX_COMPACT = 1'b1", "parameter bit SBOX_COMPACT = 1'b0")
        if new == s: sys.exit("could not switch SBOX_COMPACT default in aes_v3_fu.sv")
        open(p, "w").write(new)

    top_rel = [r for r in read_list if r.endswith("/ibex_top.sv")]
    if len(top_rel) != 1: sys.exit("ibex_top.sv not found in the file list")
    wrapper = make_wrapper(os.path.join(out, top_rel[0]))
    open(os.path.join(out, "ibex_syn_top.sv"), "w").write(wrapper)
    read_list.append("ibex_syn_top.sv")

    open(os.path.join(out, "files.txt"), "w").write("\n".join(read_list) + "\n")
    open(os.path.join(out, "incdirs.txt"), "w").write("\n".join(inc_dirs) + "\n")
    has_aes = any(r.endswith("aes_v3_fu.sv") for r in read_list)
    print(f"packed {len(read_list)} RTL files, {len(inc_dirs)} include dirs -> {out}")
    print(f"AES unit present: {has_aes}; S-box default: {'LUT' if a.lut_sbox else 'compact (as in source)'}; "
          f"clock gating: {'generic' if a.generic_clock_gating else 'Xilinx BUFGCE'}; skipped sim-only files: {n_skipped}")
    if a.zip:
        z = shutil.make_archive(out, "zip", out)
        print("wrote", z)

if __name__ == "__main__":
    main()
